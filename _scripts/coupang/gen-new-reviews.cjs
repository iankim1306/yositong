function js(v, indent) {
  const pad = ' '.repeat(indent);
  if (typeof v === 'string') return "'" + v.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) {
    if (!v.length) return '[]';
    const simple = v.every(x => typeof x === 'string' && x.length < 60);
    if (simple) return '[' + v.map(x => js(x, 0)).join(', ') + ']';
    return '[\n' + v.map(x => pad + '  ' + js(x, indent + 2)).join(',\n') + '\n' + pad + ']';
  }
  const keys = Object.keys(v);
  return '{ ' + keys.map(k => k + ': ' + js(v[k], indent + 2)).join(', ') + ' }';
}

